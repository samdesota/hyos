function patchBlock(
  id: string,
  repository: string,
  hunk: string,
): LiterateDiff["blocks"][number] {
  return {
    id,
    kind: "apply_patch",
    repository,
    title: id,
    rationale: `Apply ${id}`,
    patch: `diff --git a/state.txt b/state.txt\n--- a/state.txt\n+++ b/state.txt\n${hunk}\n`,
  };
}

