function finishRun(
  message: string,
  outcome: "changed" | "conversation" | "blocked" = "changed",
): GatewayMessage {
  return {
    role: "assistant",
    content: null,
    tool_calls: [
      {
        id: "finish",
        function: {
          name: "finish_run",
          arguments: JSON.stringify({ outcome, message }),
        },
      },
    ],
  };
}

